package PREEXAMEN;

/** //Ejercicio 7 – Repetición con FOR
Realizar un programa que muestre los números del 1 al 10 utilizando un ciclo for.

 *
 * @author juann
 */

public class EJE7 {
    public static void main(String[] args) {
       
       
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }
        
        
    }
    
}
